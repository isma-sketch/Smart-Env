package config

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/smartenv/smart-env/internal/analyzer"
)

// WriteEnvFile writes an .env file based on example order and values.
// exampleOrder: keys in example order. values: final values. extras: extra keys to append.
func WriteEnvFile(path string, exampleOrder []string, exampleVals map[string]string, values map[string]string, extras []string) error {
	var b strings.Builder
	b.WriteString("# Generated by smart-env\n")
	for _, k := range exampleOrder {
		v := values[k]
		if v == "" {
			v = exampleVals[k]
		}
		b.WriteString(fmt.Sprintf("%s=%s\n", k, quoteValue(v)))
	}
	if len(extras) > 0 {
		b.WriteString("\n# Additional variables\n")
		for _, k := range extras {
			b.WriteString(fmt.Sprintf("%s=%s\n", k, quoteValue(values[k])))
		}
	}
	return os.WriteFile(path, []byte(b.String()), 0644)
}

func quoteValue(v string) string {
	if v == "" {
		return ""
	}
	if strings.ContainsAny(v, " \t#\"'") || strings.Contains(v, "\n") {
		// escape double quotes
		v = strings.ReplaceAll(v, "\"", "\\\"")
		return "\"" + v + "\""
	}
	return v
}

// EnsureEnv creates .env from example if missing.
func EnsureEnv(root string) (string, error) {
	envPath := filepath.Join(root, ".env")
	if _, err := os.Stat(envPath); err == nil {
		return envPath, nil
	}
	// find example
	var example string
	for _, name := range []string{".env.example", ".env.template", ".env.sample"} {
		p := filepath.Join(root, name)
		if _, err := os.Stat(p); err == nil {
			example = p
			break
		}
	}
	if example == "" {
		return "", fmt.Errorf("no .env or example found")
	}
	data, err := os.ReadFile(example)
	if err != nil {
		return "", err
	}
	if err := os.WriteFile(envPath, data, 0644); err != nil {
		return "", err
	}
	return envPath, nil
}

// ReadEnvOrdered wraps analyzer.
func ReadEnvOrdered(path string) ([]string, map[string]string, error) {
	return analyzer.ParseEnvOrdered(path)
}
